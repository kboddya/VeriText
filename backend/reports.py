from __future__ import annotations

from datetime import datetime, timezone
from typing import Any, Optional

from .preprocessing import get_confidence_status


def _escape_md_table_cell(text: str) -> str:
    """Escape vertical bars and collapse newlines for clean markdown table cells."""
    if not text:
        return ""
    cleaned = text.replace("\r\n", " ").replace("\n", " ").replace("\r", " ")
    cleaned = cleaned.replace("|", r"\|")
    return " ".join(cleaned.split())


def _format_percentage(val: Any) -> str:
    try:
        f = float(val)
        return f"{f:.2f}%"
    except (ValueError, TypeError):
        return "N/A"


def generate_markdown_report(
    data: dict[str, Any],
    *,
    source_name: Optional[str] = None,
    created_at: Optional[str] = None,
) -> str:
    """
    Generate a comprehensive, GitHub-flavored Markdown inspection report in English
    for analyzed text or document.
    """
    if not created_at:
        created_at = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")

    # Resolve filename or source identifier
    resolved_source = (
        data.get("filename")
        or source_name
        or "Direct Text Input"
    )

    summary = data.get("summary") or {}
    monolithic_scale = data.get("monolithic_scale")
    if monolithic_scale is None:
        monolithic_scale = data.get("human_ai_scale", data.get("overall_scale", 50.0))
    try:
        monolithic_scale = float(monolithic_scale)
    except (ValueError, TypeError):
        monolithic_scale = 50.0

    paragraph_scale = data.get("paragraph_scale")
    if paragraph_scale is None:
        paragraph_scale = summary.get("paragraph_scale", monolithic_scale)
    try:
        paragraph_scale = float(paragraph_scale)
    except (ValueError, TypeError):
        paragraph_scale = monolithic_scale

    # Resolve confidence status
    conf = data.get("confidence_status") or summary.get("confidence_status")
    if not isinstance(conf, dict) or "grade" not in conf:
        conf = get_confidence_status(monolithic_scale)

    # Status badge icon
    status_code = conf.get("code", "")
    if status_code == "verified_human":
        status_emoji = "🟢"
    elif status_code == "likely_human":
        status_emoji = "🔵"
    elif status_code == "uncertain_borderline":
        status_emoji = "🟡"
    elif status_code == "likely_ai":
        status_emoji = "🟠"
    else:
        status_emoji = "🔴"

    model_used = data.get("model_used") or "RuBERT-AI / DeBERTa-v3"
    device = str(data.get("device") or "Auto").upper()
    req_id = data.get("request_id") or "N/A"
    mode = str(data.get("mode") or "auto").upper()

    # Metrics
    full_text = data.get("full_text") or ""
    words = summary.get("word_count")
    if words is None:
        words = len(full_text.split()) if full_text else 0
    chars = summary.get("char_count")
    if chars is None:
        chars = len(full_text) if full_text else 0

    paragraphs = data.get("paragraphs") or []
    total_paras = summary.get("total_paragraphs", len(paragraphs) if paragraphs else 1)
    analyzed_paras = summary.get("analyzed_paragraphs", len(paragraphs))
    ai_paras = summary.get("ai_paragraphs")
    if ai_paras is None:
        ai_paras = sum(1 for p in paragraphs if p.get("label") == "ai") if paragraphs else (1 if monolithic_scale >= 50 else 0)
    human_paras = summary.get("human_paragraphs")
    if human_paras is None:
        human_paras = max(0, total_paras - ai_paras)
    ai_para_pct = summary.get("ai_paragraph_pct")
    if ai_para_pct is None:
        ai_para_pct = round((ai_paras / max(1, total_paras)) * 100, 2)

    overall_label = data.get("label") or ("ai" if monolithic_scale >= 50.0 else "human")
    label_text = "AI-Generated" if overall_label == "ai" else "Human-Written"

    lines: list[str] = []

    # Title & Header
    lines.append("# 🛡️ VeriText — AI Text & Document Authenticity Report")
    lines.append("")
    lines.append("> Official analytical verification report generated by VeriText Synthetic Text Detection Engine.")
    lines.append("")

    # Metadata Table
    lines.append("## 📋 Inspection Metadata")
    lines.append("")
    lines.append("| Parameter | Value |")
    lines.append("| :--- | :--- |")
    lines.append(f"| **Inspection Timestamp** | `{created_at}` |")
    lines.append(f"| **Target Document / Source** | `{resolved_source}` |")
    lines.append(f"| **Model Architecture** | `{model_used}` |")
    lines.append(f"| **Analysis Mode** | `{mode}` |")
    lines.append(f"| **Inference Compute Device** | `{device}` |")
    if req_id != "N/A":
        lines.append(f"| **Session ID (Request ID)** | `{req_id}` |")
    lines.append("")

    # Executive Verdict
    lines.append("## 🎯 Executive Verdict & Confidence Status")
    lines.append("")
    lines.append(f"### {status_emoji} {conf.get('grade', 'Verdict')} — {conf.get('label', '')}")
    lines.append("")
    lines.append(f"> **Confidence Assessment:** {conf.get('description', '')}")
    lines.append("")
    lines.append("| Evaluation Metric | Value | Interpretation |")
    lines.append("| :--- | :---: | :--- |")
    lines.append(f"| **Continuous AI Probability (Macro Attention)** | **{_format_percentage(monolithic_scale)}** | Full-context continuous semantic evaluation |")
    lines.append(f"| **Paragraph-Weighted AI Score** | **{_format_percentage(paragraph_scale)}** | Word-weighted average across isolated sections |")
    lines.append(f"| **Synthetic Risk Level** | **{conf.get('risk_level', 'N/A')}** | Confidence reliability classification |")
    lines.append(f"| **Primary Binary Verdict** | **{label_text}** | Classification threshold: 50.0% |")
    if "score" in data and data["score"] is not None:
        lines.append(f"| **Raw Model Logit (Score)** | `{data['score']}` | Classifier logit output |")
    lines.append("")

    # Document Metrics & Statistics
    lines.append("## 📊 Document Statistics & Metrics")
    lines.append("")
    lines.append("| Metric | Value |")
    lines.append("| :--- | :--- |")
    lines.append(f"| Total Word Count | **{words:,}** |")
    lines.append(f"| Total Character Count | **{chars:,}** |")
    lines.append(f"| Total Paragraphs | **{total_paras}** |")
    lines.append(f"| Analyzed Paragraphs | **{analyzed_paras}** |")
    lines.append(f"| AI-Classified Paragraphs | **{ai_paras}** ({_format_percentage(ai_para_pct)}) |")
    lines.append(f"| Human-Classified Paragraphs | **{human_paras}** ({_format_percentage(100.0 - float(ai_para_pct))}) |")
    lines.append("")

    # Stylistic Markers
    markers = data.get("markers") or []
    lines.append("## 🔍 Generative Stylistic Markers (RLHF & LLM Clichés)")
    lines.append("")
    if markers:
        lines.append("| # | Detected Marker / Phrase | Pattern Description | Frequency |")
        lines.append("| :-: | :--- | :--- | :-: |")
        for i, m in enumerate(markers, 1):
            phrase = _escape_md_table_cell(str(m.get("phrase", "")))
            desc = _escape_md_table_cell(str(m.get("description", "")))
            count = m.get("count", 1)
            lines.append(f"| {i} | `«{phrase}»` | {desc} | **{count}** |")
        lines.append("")
    else:
        lines.append("*No synthetic generative stylistic markers or LLM clichés detected.*")
        lines.append("")

    # Paragraph Breakdown
    if paragraphs:
        lines.append("## 📑 Paragraph-by-Paragraph Breakdown")
        lines.append("")
        lines.append("| # | Classification | AI Probability | Words | Excerpt |")
        lines.append("| :-: | :---: | :---: | :-: | :--- |")
        for idx, p in enumerate(paragraphs, 1):
            p_idx = p.get("index", idx)
            p_label = p.get("label", "human")
            p_scale = p.get("human_ai_scale", 0.0)
            p_words = p.get("word_count", 0)
            p_text = str(p.get("text", "")).strip()

            icon = "🔴 AI" if p_label == "ai" else "🟢 Human"
            preview = (p_text[:85] + "…") if len(p_text) > 85 else p_text
            preview_clean = _escape_md_table_cell(preview)
            lines.append(f"| {p_idx} | {icon} | {_format_percentage(p_scale)} | {p_words} | {preview_clean} |")
        lines.append("")

        # Detailed block for each paragraph
        lines.append("### Detailed Paragraph Content")
        lines.append("")
        for idx, p in enumerate(paragraphs, 1):
            p_idx = p.get("index", idx)
            p_label = p.get("label", "human")
            p_scale = p.get("human_ai_scale", 0.0)
            p_text = str(p.get("text", "")).strip()
            p_tag = "🔴 AI-Generated" if p_label == "ai" else "🟢 Human-Written"

            lines.append(f"#### Paragraph #{p_idx} — {p_tag} ({_format_percentage(p_scale)})")
            lines.append("")
            quoted_text = "\n".join(f"> {line}" for line in p_text.splitlines()) if p_text else "> *(empty content)*"
            lines.append(quoted_text)
            lines.append("")

    # Full Analyzed Text (in collapsible section)
    if full_text and len(full_text.strip()) > 0:
        lines.append("## 📜 Full Analyzed Text")
        lines.append("")
        lines.append("<details>")
        lines.append("<summary>Click to expand full analyzed text</summary>")
        lines.append("")
        lines.append("```text")
        lines.append(full_text.strip())
        lines.append("```")
        lines.append("</details>")
        lines.append("")

    # Footer
    lines.append("---")
    lines.append("*Report automatically generated by VeriText (RuBERT-AI & DeBERTa-v3 Hybrid Inference).*")
    lines.append("")

    return "\n".join(lines)


def generate_batch_markdown_report(
    data: dict[str, Any],
    *,
    filename: Optional[str] = None,
    created_at: Optional[str] = None,
) -> str:
    """
    Generate a comprehensive Markdown report in English for a batch tabular dataset (.csv / .tsv).
    """
    if not created_at:
        created_at = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")

    resolved_filename = (
        data.get("filename")
        or filename
        or "dataset.csv"
    )

    summary = data.get("summary") or {}
    total_rows = summary.get("total_rows", data.get("total_rows", 0))
    ai_count = summary.get("ai_count", data.get("ai_count", data.get("ai_rows", 0)))
    human_count = summary.get("human_count", data.get("human_count", data.get("human_rows", 0)))
    ai_pct = summary.get("ai_percentage", data.get("ai_percentage", 0.0))
    try:
        human_pct = round(100.0 - float(ai_pct), 2)
    except (ValueError, TypeError):
        human_pct = 0.0

    text_column = summary.get("text_column") or "auto"
    mode = summary.get("mode") or data.get("mode") or "auto"
    device = summary.get("device") or data.get("device") or "auto"

    lines: list[str] = []

    lines.append("# 📊 VeriText — Batch Dataset Analysis Report")
    lines.append("")
    lines.append("> Distribution analysis of synthetic and human-written content in tabular dataset.")
    lines.append("")

    lines.append("## 📋 Dataset Metadata")
    lines.append("")
    lines.append("| Parameter | Value |")
    lines.append("| :--- | :--- |")
    lines.append(f"| **Generation Timestamp** | `{created_at}` |")
    lines.append(f"| **Dataset Filename** | `{resolved_filename}` |")
    lines.append(f"| **Target Text Column** | `{text_column}` |")
    lines.append(f"| **Model Language Mode** | `{str(mode).upper()}` |")
    lines.append(f"| **Compute Device** | `{str(device).upper()}` |")
    lines.append("")

    lines.append("## 📈 Summary Classification Results")
    lines.append("")
    lines.append("| Category | Record Count | Percentage of Dataset |")
    lines.append("| :--- | :---: | :---: |")
    lines.append(f"| **🔴 AI-Generated** | **{ai_count:,}** | **{_format_percentage(ai_pct)}** |")
    lines.append(f"| **🟢 Human-Written** | **{human_count:,}** | **{_format_percentage(human_pct)}** |")
    lines.append(f"| **Total Records Evaluated** | **{total_rows:,}** | **100.00%** |")
    lines.append("")

    preview_rows = data.get("preview_rows") or data.get("preview") or []
    if preview_rows:
        lines.append("## 🔍 Dataset Preview (First Rows)")
        lines.append("")
        cols = list(preview_rows[0].keys())
        # Filter down columns if too many for markdown table
        display_cols = cols[:8]
        header = "| " + " | ".join(display_cols) + " |"
        sep = "| " + " | ".join([":---"] * len(display_cols)) + " |"
        lines.append(header)
        lines.append(sep)

        for row in preview_rows[:15]:
            vals = []
            for col in display_cols:
                raw_val = str(row.get(col, ""))
                if len(raw_val) > 60:
                    raw_val = raw_val[:60] + "…"
                vals.append(_escape_md_table_cell(raw_val))
            lines.append("| " + " | ".join(vals) + " |")
        lines.append("")

    lines.append("---")
    lines.append("*Report automatically generated by VeriText Batch Processor.*")
    lines.append("")

    return "\n".join(lines)
