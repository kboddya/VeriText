from __future__ import annotations

from datetime import datetime, timezone
from typing import Any, Optional

from .preprocessing import get_confidence_status


def _escape_md_table_cell(text: str) -> str:
    """Escape vertical bars and collapse newlines for clean markdown table cells."""
    if not text:
        return ""
    cleaned = text.replace("\r\n", " ").replace("\n", " ").replace("\r", " ")
    cleaned = cleaned.replace("|", r"\|")
    return " ".join(cleaned.split())


def _format_percentage(val: Any) -> str:
    try:
        f = float(val)
        return f"{f:.2f}%"
    except (ValueError, TypeError):
        return "N/A"


def _safe_float(val: Any, default: float = 0.0) -> float:
    """Safely convert a value to float, returning default on None or conversion errors."""
    if val is None:
        return default
    try:
        return float(val)
    except (ValueError, TypeError):
        return default


def generate_markdown_report(
    data: dict[str, Any],
    *,
    source_name: Optional[str] = None,
    created_at: Optional[str] = None,
) -> str:
    """
    Generate a comprehensive, GitHub-flavored Markdown inspection report in English
    for analyzed text or document.
    """
    if not created_at:
        created_at = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")

    # Resolve filename or source identifier
    resolved_source = (
        data.get("filename")
        or source_name
        or "Direct Text Input"
    )

    summary = data.get("summary") or {}
    monolithic_scale = data.get("monolithic_scale")
    if monolithic_scale is None:
        monolithic_scale = data.get("human_ai_scale", data.get("overall_scale", 50.0))
    try:
        monolithic_scale = float(monolithic_scale)
    except (ValueError, TypeError):
        monolithic_scale = 50.0

    paragraph_scale = data.get("paragraph_scale")
    if paragraph_scale is None:
        paragraph_scale = summary.get("paragraph_scale", monolithic_scale)
    try:
        paragraph_scale = float(paragraph_scale)
    except (ValueError, TypeError):
        paragraph_scale = monolithic_scale

    # Resolve confidence status
    conf = data.get("confidence_status") or summary.get("confidence_status")
    if not isinstance(conf, dict) or "grade" not in conf:
        conf = get_confidence_status(monolithic_scale)

    # Status badge icon
    status_code = conf.get("code", "")
    if status_code == "verified_human":
        status_emoji = "🟢"
    elif status_code == "likely_human":
        status_emoji = "🔵"
    elif status_code == "uncertain_borderline":
        status_emoji = "🟡"
    elif status_code == "likely_ai":
        status_emoji = "🟠"
    else:
        status_emoji = "🔴"

    model_used = data.get("model_used") or "RuBERT-AI / DeBERTa-v3"
    device = str(data.get("device") or "Auto").upper()
    req_id = data.get("request_id") or "N/A"
    mode = str(data.get("mode") or "auto").upper()

    # Metrics
    full_text = data.get("full_text") or ""
    words = summary.get("word_count")
    if words is None:
        words = len(full_text.split()) if full_text else 0
    chars = summary.get("char_count")
    if chars is None:
        chars = len(full_text) if full_text else 0

    paragraphs = data.get("paragraphs") or []
    total_paras = summary.get("total_paragraphs", len(paragraphs) if paragraphs else 1)
    analyzed_paras = summary.get("analyzed_paragraphs", len(paragraphs))
    ai_paras = summary.get("ai_paragraphs")
    if ai_paras is None:
        ai_paras = sum(1 for p in paragraphs if p.get("label") == "ai") if paragraphs else (1 if monolithic_scale >= 50 else 0)
    human_paras = summary.get("human_paragraphs")
    if human_paras is None:
        human_paras = max(0, total_paras - ai_paras)
    ai_para_pct = summary.get("ai_paragraph_pct")
    if ai_para_pct is None:
        ai_para_pct = round((ai_paras / max(1, total_paras)) * 100, 2)

    overall_label = data.get("label") or ("ai" if monolithic_scale >= 50.0 else "human")
    label_text = "AI-Generated" if overall_label == "ai" else "Human-Written"

    lines: list[str] = []

    # Title & Header
    lines.append("# 🛡️ VeriText — AI Text & Document Authenticity Report")
    lines.append("")
    lines.append("> Official analytical verification report generated by VeriText Synthetic Text Detection Engine.")
    lines.append("")

    # Metadata Table
    lines.append("## 📋 Inspection Metadata")
    lines.append("")
    lines.append("| Parameter | Value |")
    lines.append("| :--- | :--- |")
    lines.append(f"| **Inspection Timestamp** | `{created_at}` |")
    lines.append(f"| **Target Document / Source** | `{resolved_source}` |")
    lines.append(f"| **Model Architecture** | `{model_used}` |")
    lines.append(f"| **Analysis Mode** | `{mode}` |")
    lines.append(f"| **Inference Compute Device** | `{device}` |")
    if req_id != "N/A":
        lines.append(f"| **Session ID (Request ID)** | `{req_id}` |")
    lines.append("")

    # Executive Verdict
    lines.append("## 🎯 Executive Verdict & Confidence Status")
    lines.append("")
    lines.append(f"### {status_emoji} {conf.get('grade', 'Verdict')} — {conf.get('label', '')}")
    lines.append("")
    lines.append(f"> **Confidence Assessment:** {conf.get('description', '')}")
    lines.append("")
    lines.append("| Evaluation Metric | Value | Interpretation |")
    lines.append("| :--- | :---: | :--- |")
    lines.append(f"| **Continuous AI Probability (Macro Attention)** | **{_format_percentage(monolithic_scale)}** | Full-context continuous semantic evaluation |")
    lines.append(f"| **Paragraph-Weighted AI Score** | **{_format_percentage(paragraph_scale)}** | Word-weighted average across isolated sections |")
    lines.append(f"| **Synthetic Risk Level** | **{conf.get('risk_level', 'N/A')}** | Confidence reliability classification |")
    lines.append(f"| **Primary Binary Verdict** | **{label_text}** | Classification threshold: 50.0% |")
    if "score" in data and data["score"] is not None:
        lines.append(f"| **Raw Model Logit (Score)** | `{data['score']}` | Classifier logit output |")
    lines.append("")

    # Document Metrics & Statistics
    lines.append("## 📊 Document Statistics & Metrics")
    lines.append("")
    lines.append("| Metric | Value |")
    lines.append("| :--- | :--- |")
    lines.append(f"| Total Word Count | **{words:,}** |")
    lines.append(f"| Total Character Count | **{chars:,}** |")
    lines.append(f"| Total Paragraphs | **{total_paras}** |")
    lines.append(f"| Analyzed Paragraphs | **{analyzed_paras}** |")
    lines.append(f"| AI-Classified Paragraphs | **{ai_paras}** ({_format_percentage(ai_para_pct)}) |")
    lines.append(f"| Human-Classified Paragraphs | **{human_paras}** ({_format_percentage(100.0 - float(ai_para_pct))}) |")
    lines.append("")

    # Stylistic Markers
    markers = data.get("markers") or []
    lines.append("## 🔍 Generative Stylistic Markers (RLHF & LLM Clichés)")
    lines.append("")
    if markers:
        lines.append("| # | Detected Marker / Phrase | Pattern Description | Frequency |")
        lines.append("| :-: | :--- | :--- | :-: |")
        for i, m in enumerate(markers, 1):
            phrase = _escape_md_table_cell(str(m.get("phrase", "")))
            desc = _escape_md_table_cell(str(m.get("description", "")))
            count = m.get("count", 1)
            lines.append(f"| {i} | `«{phrase}»` | {desc} | **{count}** |")
        lines.append("")
    else:
        lines.append("*No synthetic generative stylistic markers or LLM clichés detected.*")
        lines.append("")

    # Paragraph Breakdown
    if paragraphs:
        lines.append("## 📑 Paragraph-by-Paragraph Breakdown")
        lines.append("")
        lines.append("| # | Classification | AI Probability | Words | Excerpt |")
        lines.append("| :-: | :---: | :---: | :-: | :--- |")
        for idx, p in enumerate(paragraphs, 1):
            p_idx = p.get("index", idx)
            p_label = p.get("label", "human")
            p_scale = p.get("human_ai_scale", 0.0)
            p_words = p.get("word_count", 0)
            p_text = str(p.get("text", "")).strip()

            icon = "🔴 AI" if p_label == "ai" else "🟢 Human"
            preview = (p_text[:85] + "…") if len(p_text) > 85 else p_text
            preview_clean = _escape_md_table_cell(preview)
            lines.append(f"| {p_idx} | {icon} | {_format_percentage(p_scale)} | {p_words} | {preview_clean} |")
        lines.append("")

        # Detailed block for each paragraph
        lines.append("### Detailed Paragraph Content")
        lines.append("")
        for idx, p in enumerate(paragraphs, 1):
            p_idx = p.get("index", idx)
            p_label = p.get("label", "human")
            p_scale = p.get("human_ai_scale", 0.0)
            p_text = str(p.get("text", "")).strip()
            p_tag = "🔴 AI-Generated" if p_label == "ai" else "🟢 Human-Written"

            lines.append(f"#### Paragraph #{p_idx} — {p_tag} ({_format_percentage(p_scale)})")
            lines.append("")
            quoted_text = "\n".join(f"> {line}" for line in p_text.splitlines()) if p_text else "> *(empty content)*"
            lines.append(quoted_text)
            lines.append("")

    # Full Analyzed Text (in collapsible section)
    if full_text and len(full_text.strip()) > 0:
        lines.append("## 📜 Full Analyzed Text")
        lines.append("")
        lines.append("<details>")
        lines.append("<summary>Click to expand full analyzed text</summary>")
        lines.append("")
        lines.append("```text")
        lines.append(full_text.strip())
        lines.append("```")
        lines.append("</details>")
        lines.append("")

    # Footer
    lines.append("---")
    lines.append("*Report automatically generated by VeriText (RuBERT-AI & DeBERTa-v3 Hybrid Inference).*")
    lines.append("")

    return "\n".join(lines)


def generate_humanize_markdown_report(
    data: dict[str, Any],
    *,
    source_name: Optional[str] = None,
    filename: Optional[str] = None,
    created_at: Optional[str] = None,
) -> str:
    """
    Generate a comprehensive, GitHub-flavored Markdown transformation report
    for text or document humanized via VeriText ModernTextHumanizer.
    """
    if not created_at:
        created_at = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")

    resolved_source = (
        filename
        or source_name
        or data.get("filename")
        or "Direct Text Input"
    )

    summary = data.get("summary") or {}
    before_scale = data.get("before_scale", 0.0)
    try:
        before_scale = float(before_scale)
    except (ValueError, TypeError):
        before_scale = 0.0

    after_scale = data.get("after_scale", 0.0)
    try:
        after_scale = float(after_scale)
    except (ValueError, TypeError):
        after_scale = 0.0

    delta_scale = data.get("delta_scale")
    if delta_scale is None:
        delta_scale = round(before_scale - after_scale, 2)
    try:
        delta_scale = float(delta_scale)
    except (ValueError, TypeError):
        delta_scale = 0.0

    before_para_scale = data.get("before_paragraph_scale", before_scale)
    try:
        before_para_scale = float(before_para_scale)
    except (ValueError, TypeError):
        before_para_scale = before_scale

    after_para_scale = data.get("after_paragraph_scale", after_scale)
    try:
        after_para_scale = float(after_para_scale)
    except (ValueError, TypeError):
        after_para_scale = after_scale

    mode = str(data.get("mode") or "auto").upper()
    effective_lang = str(data.get("effective_language") or "en").upper()
    strength = str(data.get("strength") or "balanced").capitalize()
    critic_engine = str(data.get("critic_engine") or data.get("model_used") or "RuBERT-AI / DeBERTa-v3 (Detector-Guided Critic)")
    req_id = data.get("request_id") or "N/A"

    before_conf = data.get("before_confidence")
    if not isinstance(before_conf, dict) or "grade" not in before_conf:
        before_conf = get_confidence_status(before_scale)

    after_conf = data.get("after_confidence")
    if not isinstance(after_conf, dict) or "grade" not in after_conf:
        after_conf = get_confidence_status(after_scale)

    orig_text = data.get("original_text") or ""
    humanized_text = data.get("humanized_text") or ""

    words_before = summary.get("word_count_before")
    if words_before is None:
        words_before = len(orig_text.split()) if orig_text else 0

    words_after = summary.get("word_count_after")
    if words_after is None:
        words_after = len(humanized_text.split()) if humanized_text else 0

    chars_before = summary.get("char_count_before")
    if chars_before is None:
        chars_before = len(orig_text) if orig_text else 0

    chars_after = summary.get("char_count_after")
    if chars_after is None:
        chars_after = len(humanized_text) if humanized_text else 0

    paragraphs = data.get("paragraphs") or []
    total_paras = summary.get("total_paragraphs", len(paragraphs) if paragraphs else 1)
    modified_paras = summary.get("modified_paragraphs_count")
    if modified_paras is None:
        modified_paras = sum(1 for p in paragraphs if p.get("original_text") != p.get("humanized_text"))

    removed_markers = data.get("removed_markers") or []
    removed_cliches_count = summary.get("removed_cliches_count", len(removed_markers))

    lines: list[str] = []

    # Title & Header
    lines.append("# ✨ VeriText — AI Text Humanization & Transformation Report")
    lines.append("")
    lines.append("> Zero-training, detector-guided text transformation and AI score reduction audit.")
    lines.append("")

    # Transformation Metadata Table
    lines.append("## 📋 Transformation Metadata")
    lines.append("")
    lines.append("| Parameter | Value |")
    lines.append("| :--- | :--- |")
    lines.append(f"| **Transformation Timestamp** | `{created_at}` |")
    lines.append(f"| **Target Document / Source** | `{resolved_source}` |")
    lines.append(f"| **Language Mode** | `{mode}` (Effective: `{effective_lang}`) |")
    lines.append(f"| **Humanization Strength** | `{strength}` |")
    lines.append(f"| **Critic Engine Architecture** | `{critic_engine}` |")
    if req_id != "N/A":
        lines.append(f"| **Session ID (Request ID)** | `{req_id}` |")
    lines.append("")

    # Executive Verdict & Confidence Evolution
    lines.append("## 🎯 Executive Verdict & Confidence Evolution")
    lines.append("")
    b_grade = before_conf.get("grade", "Grade")
    b_label = before_conf.get("label", "")
    a_grade = after_conf.get("grade", "Grade")
    a_label = after_conf.get("label", "")
    lines.append(f"### {b_grade} ({b_label}) → {a_grade} ({a_label})")
    lines.append("")
    lines.append(f"> **Net AI Reduction:** **-{_format_percentage(delta_scale)}** (Baseline: {_format_percentage(before_scale)} → Transformed: {_format_percentage(after_scale)})")
    lines.append("")
    lines.append("| Transformation Metric | Baseline (Before) | Transformed (After) | Net Change |")
    lines.append("| :--- | :---: | :---: | :---: |")
    lines.append(f"| **Continuous AI Probability** | **{_format_percentage(before_scale)}** | **{_format_percentage(after_scale)}** | **-{_format_percentage(delta_scale)}** |")
    p_delta = round(before_para_scale - after_para_scale, 2)
    lines.append(f"| **Paragraph-Weighted AI Score** | **{_format_percentage(before_para_scale)}** | **{_format_percentage(after_para_scale)}** | **-{_format_percentage(p_delta)}** |")
    lines.append(f"| **Confidence Status Grade** | {b_grade} ({b_label}) | {a_grade} ({a_label}) | Improved |")
    lines.append(f"| **Modified Paragraphs** | 0 / {total_paras} | {modified_paras} / {total_paras} | {modified_paras} transformed |")
    lines.append(f"| **Scrubbed Clichés Count** | 0 | {removed_cliches_count} | {removed_cliches_count} scrubbed |")
    lines.append(f"| **Word / Character Count** | {words_before:,} / {chars_before:,} | {words_after:,} / {chars_after:,} | {words_after - words_before:+d} words |")
    lines.append("")

    # Scrubbed Generative Clichés & Markers
    lines.append("## 🔍 Scrubbed Generative Clichés & Stylistic Markers")
    lines.append("")
    if removed_markers:
        lines.append("| # | Detected Marker / Phrase | Pattern Description | Replacement Applied | Frequency |")
        lines.append("| :-: | :--- | :--- | :--- | :-: |")
        for i, m in enumerate(removed_markers, 1):
            phrase = _escape_md_table_cell(str(m.get("phrase", "")))
            desc = _escape_md_table_cell(str(m.get("category") or m.get("description", "Formulaic transition")))
            replacement = _escape_md_table_cell(str(m.get("replacement", "*(scrubbed)*")))
            count = m.get("count", 1)
            lines.append(f"| {i} | `«{phrase}»` | {desc} | `{replacement}` | **{count}** |")
        lines.append("")
    else:
        lines.append("*No generative clichés or synthetic boilerplate markers detected.*")
        lines.append("")

    # Paragraph-by-Paragraph Breakdown
    if paragraphs:
        lines.append("## 📑 Paragraph-by-Paragraph Transformation Breakdown")
        lines.append("")
        lines.append("| # | Status | Original AI % | Humanized AI % | Net Delta | Stage Applied | Excerpt Diff |")
        lines.append("| :-: | :---: | :---: | :---: | :---: | :---: | :--- |")
        for idx, p in enumerate(paragraphs, 1):
            p_idx = p.get("index", idx)
            b_sc = _safe_float(p.get("before_scale"), 0.0)
            a_sc = _safe_float(p.get("after_scale"), 0.0)
            d_sc = _safe_float(p.get("delta_scale"), round(b_sc - a_sc, 2))
            stage = p.get("stage_applied", "full")
            if stage == "code" or p.get("is_code"):
                p_status = "🔵 Code"
            else:
                p_status = "🟢 Human" if a_sc < 50.0 else "🔴 AI"

            hum_p_text = str(p.get("humanized_text", "")).strip()
            preview = (hum_p_text[:75] + "…") if len(hum_p_text) > 75 else hum_p_text
            preview_clean = _escape_md_table_cell(preview)
            lines.append(
                f"| {p_idx} | {p_status} | {_format_percentage(b_sc)} | {_format_percentage(a_sc)} | -{_format_percentage(d_sc)} | `{stage}` | {preview_clean} |"
            )
        lines.append("")

        # Detailed Comparison Blocks
        lines.append("### Detailed Paragraph Comparisons")
        lines.append("")
        for idx, p in enumerate(paragraphs, 1):
            p_idx = p.get("index", idx)
            b_sc = _safe_float(p.get("before_scale"), 0.0)
            a_sc = _safe_float(p.get("after_scale"), 0.0)
            stage = p.get("stage_applied", "full")
            is_c = (stage == "code" or bool(p.get("is_code")))
            p_status = "🔵 Code (Preserved)" if is_c else ("🟢 Human-Verified" if a_sc < 50.0 else "🔴 AI-Biased")
            orig_p_text = str(p.get("original_text", "")).strip()
            hum_p_text = str(p.get("humanized_text", "")).strip()

            if is_c:
                lines.append(f"#### Paragraph #{p_idx} — {p_status} [Stage: `code`]")
                lines.append("")
                lines.append("```text")
                lines.append(orig_p_text)
                lines.append("```")
                lines.append("")
            else:
                lines.append(f"#### Paragraph #{p_idx} — {p_status} ({_format_percentage(b_sc)} → {_format_percentage(a_sc)}) [Stage: `{stage}`]")
                lines.append("")
                lines.append("**Original Text:**")
                lines.append("\n".join(f"> {line}" for line in orig_p_text.splitlines()) if orig_p_text else "> *(empty content)*")
                lines.append("")
                lines.append("**Humanized Text:**")
                lines.append("\n".join(f"> {line}" for line in hum_p_text.splitlines()) if hum_p_text else "> *(empty content)*")
                lines.append("")

    # Full Transformed Text
    if humanized_text and len(humanized_text.strip()) > 0:
        lines.append("## 📜 Full Transformed Text")
        lines.append("")
        lines.append("<details>")
        lines.append("<summary>Click to expand full humanized text</summary>")
        lines.append("")
        lines.append("```text")
        lines.append(humanized_text.strip())
        lines.append("```")
        lines.append("</details>")
        lines.append("")

    # Footer
    lines.append("---")
    lines.append("*Report automatically generated by VeriText AI Text Humanizer.*")
    lines.append("")

    return "\n".join(lines)

